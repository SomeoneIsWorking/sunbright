extern "C" void sbr_vptr_note(unsigned obj);

namespace {

// Guest field offsets. JDrama::TPlacement::mPosition @ 0x10, JDrama::TActor::mRotation @ 0x30
// (decomp include/JSystem/JDrama/JDRPlacement.hpp, JDRActor.hpp). Guest floats are big-endian.
constexpr u32 OFF_POSITION = 0x10;
constexpr u32 OFF_ROTATION = 0x30;

constexpr u32 CUE_MOVE  = 0x1;
constexpr u32 CUE_CALC_ANIM = 0x2;   // calcRootMatrix runs HERE, not in the draw phase

// SBR_INTERP60_ALPHA: write lerp(prev, cur, alpha) into the guest transform for the draw phase.
// Unset means snapshot-only (read nothing back). alpha=1.0 MUST be pixel-identical to unset --
// that is the control for the write path itself, before interpolation is attempted. alpha=0.0
// renders the PREVIOUS tick's pose and must visibly differ, or the write is reaching nothing.
float alpha_setting() {
    static const float a = [] {
        const char* e = std::getenv("SBR_INTERP60_ALPHA");
        return e ? (float)std::atof(e) : -1.0f;
    }();
    return a;
}

bool enabled() {
    static const bool on = std::getenv("SBR_INTERP60") != nullptr;
    return on;
}

float guest_f32(u32 ea) {
    const u32 bits = sb_r32(ea);
    float f;
    __builtin_memcpy(&f, &bits, sizeof f);
    return f;
}

bool is_tactor(u32 vptr) {
    // kTActorVtables is emitted sorted; binary search keeps this off the profile.
    int lo = 0, hi = (int)(sizeof(kTActorVtables) / sizeof(kTActorVtables[0])) - 1;
    while (lo <= hi) {
        const int mid = (lo + hi) / 2;
        if (kTActorVtables[mid] == vptr) return true;
        if (kTActorVtables[mid] < vptr) lo = mid + 1; else hi = mid - 1;
    }
    return false;
}

// ── (prev) side table ────────────────────────────────────────────────────────
// Keyed by guest address. A guest object can be freed and its address reused, so every entry
// carries the tick it was written on; an entry older than one tick is treated as absent rather
// than interpolated from, which would otherwise blend a dead object's transform into a live one.
// Open-addressed and fixed-size: no allocation on the game thread.
constexpr int TABLE_BITS = 13;                 // 8192 slots
constexpr int TABLE_SIZE = 1 << TABLE_BITS;
constexpr int TABLE_MASK = TABLE_SIZE - 1;

struct Entry {
    u32   obj  = 0;        // guest address, 0 = empty
    u32   tick = 0;
    float pos[3] = {0, 0, 0};   // (prev): transform before this tick's movement
    float rot[3] = {0, 0, 0};
    float cur[3] = {0, 0, 0};   // (cur): saved at apply time so restore is exact
    float curRot[3] = {0, 0, 0};
    bool  applied = false;      // a lerp is currently written into guest memory
};

Entry g_tab[TABLE_SIZE];
long  g_evictions = 0;     // a full probe chain: capacity exceeded, and it must be visible

Entry* slot_for(u32 obj) {
    u32 h = obj * 2654435761u;
    for (int i = 0; i < 64; ++i) {
        Entry& e = g_tab[(h + (u32)i) & TABLE_MASK];
        if (e.obj == obj || e.obj == 0) return &e;
    }
    ++g_evictions;
    return nullptr;
}

// ── motion probe ─────────────────────────────────────────────────────────────
// Designed negative-first: "interpolation changed nothing" cannot distinguish a correct
// implementation from a snapshot that captures nothing, so this always reports its DENOMINATOR and
// names the largest mover. If the biggest mover is an ambient prop rather than the player, the
// allowlist is missing the things that matter and the name says so.
long        g_samples = 0, g_moved = 0, g_nonActors = 0, g_actors = 0;
long        g_applied = 0, g_restored = 0;
long        g_writeStuck = 0, g_writeLost = 0;
// The tick value the most recent snapshot was stamped with. apply_all() keys on THIS rather than
// on VIGetRetraceCount(): the draw-phase dispatch does not reliably share the present counter's
// value with the movement dispatch (direct() has an entry-vs-render alternation), so requiring
// exact equality with the present counter matched no entries and the write silently never fired.
u32         g_lastSnapTick = 0xFFFFFFFFu;
float       g_maxStep = 0.0f;
u32         g_maxObj = 0;
float       g_tickMaxStep = 0.0f;   // per-window, so one init teleport cannot mask the steady state
u32         g_tickMaxObj = 0;
unsigned    g_lastReport = 0;

// Read a TNameRef's name (vptr @ 0x00, const char* mName @ 0x04). The largest mover must be
// NAMED: "maxStep=2200" is equally consistent with the player walking and with one prop teleporting
// once at init, and only the name separates them.
void guest_name(u32 obj, char* out, size_t cap) {
    out[0] = '\0';
    if (!sb_ram_fast(obj)) return;
    const u32 p = sb_r32(obj + 4);
    if (!sb_ram_fast(p)) { std::snprintf(out, cap, "<unreadable>"); return; }
    size_t i = 0;
    for (; i + 1 < cap; ++i) {
        const u8 c = sb_r8(p + (u32)i);
        if (c == 0) break;
        out[i] = (char)c;
    }
    out[i] = '\0';
}

void report() {
    char nm[48]; guest_name(g_maxObj, nm, sizeof nm);
    char tick_nm[48]; guest_name(g_tickMaxObj, tick_nm, sizeof tick_nm);
    lucent::info("interp60",
                 "SNAPSHOT: dispatches={} (tactor={} non-actor={}) | compared={} moved={} ({:.1f}%) "
                 "| maxStep all-time={:.2f} \"{}\"  this-window={:.2f} \"{}\"  evictions={}",
                 g_actors + g_nonActors, g_actors, g_nonActors, g_samples, g_moved,
                 g_samples ? 100.0 * (double)g_moved / (double)g_samples : 0.0,
                 (double)g_maxStep, nm, (double)g_tickMaxStep, tick_nm, g_evictions);
    if (alpha_setting() >= 0.0f)
        lucent::info("interp60", "  WRITE alpha={:.2f}: applied={} restored={} (unequal counts mean "
                                 "a pose was left interpolated into the physics step)",
                     (double)alpha_setting(), g_applied, g_restored);
    if (g_writeStuck || g_writeLost)
        lucent::info("interp60", "  WRITE READ-BACK: stuck={} lost={} (lost>0 means the store never "
                                 "reached the memory the guest reads)", g_writeStuck, g_writeLost);
    g_tickMaxStep = 0.0f; g_tickMaxObj = 0;
    lucent::info("interp60",
                 "  COVERS objects dispatched with CUE_MOVE whose vptr is in kTActorVtables "
                 "(694 entries, validated 47/47 precision on a live frame). Does NOT cover actors "
                 "whose vtable was not recovered, nor non-transform state (JPA particles).");
}

void guest_w_f32(u32 ea, float v) {
    u32 bits;
    __builtin_memcpy(&bits, &v, sizeof bits);
    sb_w32(ea, bits);
}

// Put the guest transforms back exactly as the game left them. Called before movement runs, so
// physics never sees an interpolated pose -- the interpolation is a RENDER-time substitution only,
// which is the whole point of interpolating instead of ticking logic at 60 Hz.
// SBR_INTERP60_NORESTORE=1: leave the substitution in place permanently. Discriminates "the render
// never reads mPosition after the apply" from "restore runs before the render does". Wrong for real
// use -- physics then runs on a substituted pose -- but it is the only way to tell those apart.
bool no_restore() {
    static const bool v = std::getenv("SBR_INTERP60_NORESTORE") != nullptr;
    return v;
}

void restore_all() {
    if (no_restore()) return;
    for (int i = 0; i < TABLE_SIZE; ++i) {
        Entry& e = g_tab[i];
        if (!e.applied) continue;
        e.applied = false;
        if (!sb_ram_fast(e.obj)) continue;
        guest_w_f32(e.obj + OFF_POSITION + 0, e.cur[0]);
        guest_w_f32(e.obj + OFF_POSITION + 4, e.cur[1]);
        guest_w_f32(e.obj + OFF_POSITION + 8, e.cur[2]);
        guest_w_f32(e.obj + OFF_ROTATION + 0, e.curRot[0]);
        guest_w_f32(e.obj + OFF_ROTATION + 4, e.curRot[1]);
        guest_w_f32(e.obj + OFF_ROTATION + 8, e.curRot[2]);
        ++g_restored;
    }
}

// Substitute lerp(prev, cur, alpha) for the draw phase. `cur` is read here rather than tracked
// separately, so restore_all() writes back exactly what the game computed -- no drift from a
// value reconstructed out of the lerp.
void apply_all(u32 tick, float alpha) {
    for (int i = 0; i < TABLE_SIZE; ++i) {
        Entry& e = g_tab[i];
        if (e.obj == 0 || e.tick != tick || e.applied) continue;
        if (!sb_ram_fast(e.obj)) continue;
        for (int k = 0; k < 3; ++k) {
            e.cur[k]    = guest_f32(e.obj + OFF_POSITION + (u32)k * 4);
            e.curRot[k] = guest_f32(e.obj + OFF_ROTATION + (u32)k * 4);
        }
        e.applied = true;

        // SBR_INTERP60_KICK=<units>: POSITIVE CONTROL for the write path. alpha=0.0 producing an
        // identical frame is ambiguous — it means either the write reaches nothing, or (prev, cur)
        // are equal for everything actually on screen. A large constant displacement removes that
        // ambiguity: if the frame still does not change, the write provably never reaches rendered
        // state, and no amount of refining the lerp would have shown it.
        static const float kick = [] {
            const char* e2 = std::getenv("SBR_INTERP60_KICK");
            return e2 ? (float)std::atof(e2) : 0.0f;
        }();
        if (kick != 0.0f) {
            const float want = e.cur[1] + kick;
            guest_w_f32(e.obj + OFF_POSITION + 4, want);
            // READ-BACK CHECK. "The write had no visible effect" has two causes that look the same:
            // the store did not stick, or it stuck and nothing read it. Only a read-back separates
            // them, and it must be counted rather than assumed.
            const float got = guest_f32(e.obj + OFF_POSITION + 4);
            if (got == want) ++g_writeStuck; else ++g_writeLost;
            ++g_applied;
            continue;
        }
        // ENDPOINT EXACTNESS is a correctness requirement, not a nicety. alpha=1.0 must reproduce
        // the game's own transform BIT-FOR-BIT, because that is the control proving the write path
        // is a no-op when it should be. `p + (c-p)*a` fails it: the subtraction and the addition
        // each round, so a=1 does not return c and the frame differed by 7,273 pixels. Writing the
        // endpoints directly, and using the (1-a)*p + a*c form in between, is exact at both ends.
        if (alpha >= 1.0f) {
            for (int k = 0; k < 3; ++k) {
                guest_w_f32(e.obj + OFF_POSITION + (u32)k * 4, e.cur[k]);
                guest_w_f32(e.obj + OFF_ROTATION + (u32)k * 4, e.curRot[k]);
            }
            ++g_applied;
            continue;
        }
        if (alpha <= 0.0f) {
            for (int k = 0; k < 3; ++k) {
                guest_w_f32(e.obj + OFF_POSITION + (u32)k * 4, e.pos[k]);
                guest_w_f32(e.obj + OFF_ROTATION + (u32)k * 4, e.rot[k]);
            }
            ++g_applied;
            continue;
        }
        for (int k = 0; k < 3; ++k) {
            guest_w_f32(e.obj + OFF_POSITION + (u32)k * 4,
                        (1.0f - alpha) * e.pos[k] + alpha * e.cur[k]);
            // Angles are Euler degrees here; a naive lerp is wrong across the +-180 seam. Take the
            // shortest arc rather than sweeping the long way round, which would spin an actor a
            // full turn in one sub-frame whenever it crossed the wrap point.
            float d = e.curRot[k] - e.rot[k];
            while (d > 180.0f)  d -= 360.0f;
            while (d < -180.0f) d += 360.0f;
            guest_w_f32(e.obj + OFF_ROTATION + (u32)k * 4, e.rot[k] + d * alpha);
        }
        ++g_applied;
    }
}

// SBR_INTERP60_TRACE=1: the ORDER of phase dispatches relative to the present boundary, for a few
// ticks. Two placements of apply/restore have now been derived by reasoning about that order and
// both were wrong -- the first left the substitution invisible, the second froze every actor by
// writing stale values over movement the game had already done. The order is cheap to observe and
// expensive to guess.
bool trace_on() {
    static const bool v = std::getenv("SBR_INTERP60_TRACE") != nullptr;
    return v;
}
long g_traceLines = 0;
u32  g_lastTraceMask = 0xFFFFFFFFu;

void trace_dispatch(u32 mask) {
    if (!trace_on() || g_traceLines > 90) return;
    if (mask == g_lastTraceMask) return;          // collapse runs; only transitions matter
    g_lastTraceMask = mask;
    ++g_traceLines;
    lucent::info("i60trace", "  dispatch mask=0x{:x}", mask);
}

void snapshot(CPUState& cpu, u32 mask) {
    const u32 obj = (u32)cpu.gpr[3];
    if (!sb_ram_fast(obj)) return;
    if (!(mask & CUE_MOVE)) return;

    const u32 vptr = sb_r32(obj);
    if (!is_tactor(vptr)) { ++g_nonActors; return; }
    ++g_actors;

    Entry* e = slot_for(obj);
    if (!e) return;

    const u32 tick = VIGetRetraceCount();
    const float px = guest_f32(obj + OFF_POSITION + 0);
    const float py = guest_f32(obj + OFF_POSITION + 4);
    const float pz = guest_f32(obj + OFF_POSITION + 8);

    if (e->obj == obj && e->tick + 1 >= tick && e->tick != tick) {
        // A live (prev) from the previous tick: measure the step interpolation would cover.
        const float dx = px - e->pos[0], dy = py - e->pos[1], dz = pz - e->pos[2];
        const float d2 = dx * dx + dy * dy + dz * dz;
        ++g_samples;
        if (d2 > 0.0f) {
            ++g_moved;
            const float d = std::sqrt(d2);
            if (d > g_maxStep) { g_maxStep = d; g_maxObj = obj; }
            if (d > g_tickMaxStep) { g_tickMaxStep = d; g_tickMaxObj = obj; }
        }
    }

    if (e->obj == obj && e->tick == tick) return;   // already snapshotted this tick

    e->obj = obj;
    e->tick = tick;
    g_lastSnapTick = tick;
    e->pos[0] = px; e->pos[1] = py; e->pos[2] = pz;
    e->rot[0] = guest_f32(obj + OFF_ROTATION + 0);
    e->rot[1] = guest_f32(obj + OFF_ROTATION + 4);
    e->rot[2] = guest_f32(obj + OFF_ROTATION + 8);
}

void interp_test_perform(CPUState& cpu) {
    if (std::getenv("SBR_VPTR_DUMP")) sbr_vptr_note((unsigned)cpu.gpr[3]);

    if (enabled()) {
        const u32 mask = (u32)cpu.gpr[4];
        const u32 tick = VIGetRetraceCount();
        const float alpha = alpha_setting();

        if (alpha >= 0.0f) {
            static u32 s_moveTick = 0xFFFFFFFFu, s_drawTick = 0xFFFFFFFFu;
            // Restore BEFORE this tick's movement: physics must never run on an interpolated pose.
            // Restore at the first MOVEMENT dispatch, not at the present. Measured: restoring at
            // the present boundary writes stale values over movement the game has already done —
            // `moved` collapsed from 1.9% to 0.0% and every actor froze. The trace explains it: a
            // direct() call runs draw -> move -> calc -> view -> entry -> present, so the present
            // is AFTER that call's movement, and a restore there undoes it.
            if ((mask & CUE_MOVE) && tick != s_moveTick) { s_moveTick = tick; restore_all(); }
            // Substitute before the CALC phase, NOT before draw. calcRootMatrix() -- which turns
            // mPosition/mRotation into the model's base TRMtx -- runs on CUE_CALC_ANIM (0x2), which
            // precedes entry and draw. Applying at the draw dispatch is too late: the matrix has
            // already been built from the un-interpolated pose, so the write lands in memory nobody
            // reads again that frame. Measured: with the apply at draw time, alpha=0.0 changed 0 of
            // 1,228,800 pixels while identity at alpha=1.0 passed -- the control is the only reason
            // that looked like a failure rather than a success.
            if ((mask & CUE_CALC_ANIM) && tick != s_drawTick) {
                s_drawTick = tick;
                apply_all(g_lastSnapTick, alpha);
            }
        }

        trace_dispatch(mask);

        // testPerform masks the incoming cue with the object's own unkC before dispatching; the
        // snapshot only needs to know movement is about to run for this object, and the raw cue
        // carries that. Reading it before the body keeps this a pure observation.
        snapshot(cpu, mask);

        const unsigned frame = VIGetRetraceCount();
        if (frame >= g_lastReport + 600) { g_lastReport = frame; report(); }
    }

    func_802fcc94(cpu);
}

} // namespace

// Called from native_frame.cpp's present path, after aurora has consumed the frame's GX stream and
// before the next tick's movement runs. See the call site for why it cannot be earlier.
extern "C" void sbr_interp60_restore() {
    if (!enabled()) return;
    // Trace marker only. The restore itself is NOT done here — see the movement-dispatch comment.
    if (trace_on() && g_traceLines <= 90) { ++g_traceLines; lucent::info("i60trace", "PRESENT"); }
}


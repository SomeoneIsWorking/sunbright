// The sub-frame. Called from native_frame.cpp immediately after the tick's own present, with a
// callback that closes the GX stream and presents it.
//
// It REFUSES rather than degrades: no director, no recorded draw block, no TGraphics snapshot, or
// no snapshot tick means no sub-frame, counted and reported. A sub-frame that quietly renders
// nothing would show up as "60fps that looks like 30" with no way to tell it from a bad alpha.
extern "C" void sbr_interp60_subframe(CPUState& cpu, void (*present)(void)) {
    if (!enabled()) return;
    // RE-ENTRANCY. The re-issued lists are ordinary guest code and may reach the frame seam again
    // (anything in them that waits on a retrace does). Without this guard each nesting level starts
    // another sub-frame and the frame never completes -- which presents as a hang, not as an error.
    if (g_inSubframe) return;
    ++g_gameTick;
    g_sawMovement = false;          // next tick records its own draw block
    if (!g_mardir) resolve_mardir();

    const float alpha = alpha_setting();
    if (alpha < 0.0f) { g_drawN = 0; return; }
    // Say what this run is actually doing, once. An ablation whose two alphas are set by
    // environment is otherwise invisible in its own log, and a run mislabelled in the shell is
    // indistinguishable from a result.
    {
        static bool said = false;
        if (!said) { said = true;
            lucent::info("i60sub", "alphas: camera={:.2f}  actors={:.2f}  (SBR_INTERP60_ALPHA={:.2f})",
                         (double)alpha_cam(), (double)alpha_act(), (double)alpha);
        }
    }
    if (!g_mardir || g_drawN == 0 || !g_gfxValid || g_lastSnapTick == 0xFFFFFFFFu) {
        ++g_subframeSkips;
        g_drawN = 0;
        return;
    }

    const u32 preEntry = sb_r32(g_mardir + OFF_PREENTRY);

    // Carve the TGraphics and a call frame below the seam's stack. The guest stack grows down and
    // the seam is far from the deepest frame the game uses, so this region is dead space; the old
    // recomp-era implementation used the same construction.
    const u32 savedSp = (u32)cpu.gpr[1];
    const u32 gfx = (savedSp - 0x110u) & ~0xFu;
    for (u32 i = 0; i < 0x100; ++i) sb_w8(gfx + i, g_gfxSnap[i]);
    cpu.gpr[1] = (gfx - 0x20u) & ~0xFu;

    g_inSubframe = true;
    g_subframeGfx = gfx;
    const u32 cue = subframe_cue();

    float viewBefore[12];
    for (int i = 0; i < 12; ++i) viewBefore[i] = guest_f32(gfx + OFF_VIEWMTX + (u32)i * 4);
    g_camDispatches = 0;
    const unsigned long xfbBefore = sbr_gxfifo_xfb_copies();

    // NO SEPARATE PreEntry -- and that is a POSITIVE design point, not an omission.
    //
    // TSmJ3DScn::perform (decomp JDRSmJ3DScn.cpp:46) does the whole cycle inside its DRAW cue:
    //
    //     if (param_1 & 8) {
    //         for (i < mDrawBufferCount) mDrawBuffers[i]->frameInit();   // reset
    //         j3dSys.setDrawBuffer(mDrawBuffers[0], 0); ...
    //         TViewObjPtrListT::perform(param_1 | 0x204, param_2);        // enter
    //         mDrawBuffers[0]->draw(); mDrawBuffers[1]->draw();          // draw
    //     }
    //
    // So re-issuing the draw lists resets the scene's buffers and re-enters every object from the
    // pose that is live AT THAT MOMENT -- which is exactly the substitution this file wrote. The
    // scene is self-healing too: the next tick's render branch runs the same reset-enter-draw from
    // the restored pose, so nothing has to be undone.
    //
    // Re-running PreEntry on top of that appended a SECOND entry set into buffers the seam finds
    // already full (PreEntry is the last list of a tick, and its entries are drawn by the NEXT
    // call's render branch -- the entry-vs-render alternation MarDirectorDirect.cpp documents at
    // its ENTRY-side/RENDER-side branches). The following draw then never finished.
    //
    // Measured both ways with the reach probe (tools/interp/interp60_gate.sh --kick 3000):
    // without PreEntry the sub-frame moves 1,193,906 of 1,228,800 pixels (97.16%); the earlier
    // draw-phase bracket moved 0. SBR_INTERP60_PREENTRY=1 restores the old behaviour for A/B and
    // is expected to wedge -- it is kept because a fault this specific should stay reproducible.
    static const bool preEntry_ = std::getenv("SBR_INTERP60_PREENTRY") != nullptr;
    const bool noEntry = !preEntry_;

    // Pass 1: interpolated pose -> enter -> draw -> present.
    apply_all(g_lastSnapTick, alpha_act());
    const CamSave camSave = camera_apply(cpu, g_camObj ? g_camObj : g_placeObjs[0], alpha_cam());
    // SBR_INTERP60_CALCANIM=1 — a HYPOTHESIS TEST, not a fix.
    //
    // The ablation says the actor alpha changes not one byte of the frame while the camera alpha
    // changes all of it, and the per-sub-frame tally says the substitution is not idle: 400 entries
    // written, 8 of them genuinely moved, the largest by ~20 units, one of them Mario. So the pose
    // reaches guest memory and does not reach a pixel.
    //
    // The candidate cause is a phase boundary, and it is the same shape as the camera's. An actor's
    // pose becomes geometry in TLiveActor::perform's 0x2 branch (calcRootMatrix + MActor::calc,
    // decomp src/Strategic/liveactor.cpp:401), and that bit is dispatched by the director's
    // CALC-ANIM list (+0x2C) -- NOT by the draw lists, which the actor is registered in with the
    // draw cue. The sub-frame re-issues only the draw block, so nothing recomputes a root matrix
    // from the substituted pose. The camera escaped this because its view path lives in the draw
    // lists and camera_apply rebuilt its cached matrix directly.
    //
    // Re-issuing calc-anim ALSO advances every animation a second time -- the known 30 Hz residual
    // this file already records. That is why this is a switch and not a default: it answers whether
    // the boundary is the cause, and the fix (suppressing only the frame ADVANCE) is a narrower
    // seam that should be built only once the cause is confirmed rather than assumed.
    static const bool calcAnim = std::getenv("SBR_INTERP60_CALCANIM") != nullptr;
    if (calcAnim) {
        const u32 ca = sb_r32(g_mardir + 0x2C);
        if (!ca || !sb_ram_fast(ca)) {
            static bool said = false;
            if (!said) { said = true;
                lucent::info("i60sub", "SBR_INTERP60_CALCANIM: director +0x2C is 0x{:08x}, which is "
                                       "not usable memory -- calc-anim was NOT re-issued and this "
                                       "run tests nothing.", ca);
            }
        } else {
            perform_list(cpu, ca, cue, gfx);
        }
    }
    viewseq_begin();
    if (!noEntry) perform_list(cpu, preEntry, cue, gfx);
    // SBR_INTERP60_DROPLAST=1: omit the last recorded draw list from the re-issue.
    //
    // A PLUMBING control that does not involve poses at all. Every pose-based test so far has
    // produced a sub-frame byte-identical to its main neighbour, across four configurations, which
    // is equally consistent with "the substitution reaches nothing" and with "the sub-frame's GX
    // stream never reaches the present and the main frame is simply shown twice". Dropping a whole
    // draw list MUST change the image if the sub-frame is rendered from its own stream. If the pair
    // is still 0 with a list missing, the presented sub-frame is not the sub-frame.
    static const bool dropLast = std::getenv("SBR_INTERP60_DROPLAST") != nullptr;
    const int drawN = dropLast && g_drawN > 1 ? g_drawN - 1 : g_drawN;
    for (int i = 0; i < drawN; ++i) perform_list(cpu, g_drawLists[i], g_drawCues[i] & cue, gfx);
    viewseq_end();
    // Does the substituted camera pose SURVIVE the re-issue?
    //
    // The camera's own perform runs inside the re-issue (measured: 16 dispatches), and
    // CPolarSubCamera::perform is the camera's update, not merely a matrix build. If it recomputes
    // mPosition from its internal state (angle, distance, target chase), it overwrites the lerp
    // before C_MTXLookAt ever reads it — and the sub-frame renders pose N, which is exactly what the
    // pixel gate reports. Substituting a field that its owner recomputes is futile, and no amount of
    // correct lerping fixes it; the fix would be to snapshot the state the recompute reads instead.
    if (g_camObj && sb_ram_fast(g_camObj)) {
        static long n = 0;
        if (++n <= 4 || (n % 300) == 0) {
            const float x = guest_f32(g_camObj + OFF_POSITION);
            const float z = guest_f32(g_camObj + OFF_POSITION + 8);
            lucent::info("i60sub",
                         "camera pose after re-issue #{}: ({:.2f}, _, {:.2f})   lerp wrote "
                         "({:.2f}, _, {:.2f})   cur is ({:.2f}, _, {:.2f}){}",
                         n, (double)x, (double)z, (double)g_camWrote[0], (double)g_camWrote[2],
                         (double)g_camCur[0], (double)g_camCur[2],
                         (x == g_camCur[0] && z == g_camCur[2] && g_camWrote[0] != g_camCur[0])
                             ? "   <-- REVERTED to cur: the camera recomputed its own position "
                               "during the re-issue and discarded the substitution" : "");
        }
    }

    // THE COPY. Without it the sub-frame is invisible.
    //
    // Measured: a sub-frame emitted 1.7 MB of geometry and produced a frame pixel-identical to the
    // main frame before it, in every configuration -- because it rendered into the EFB and nothing
    // copied the EFB out. `copy-to-XFB triggers emitted by this sub-frame: 0`. The display keeps
    // showing the previous image however much was drawn.
    //
    // The copy lives in TDisplay::endRendering (JDRDisplay.cpp:36), which calls waitForRetrace and
    // then IssueGXCopyDisp -> GXCopyDisp. Calling the game's own endRendering is the faithful way to
    // emit it: the copy's parameters (src rect, Y scale, dst width, clamp, filter, clear) come from
    // the display's own render mode, and reproducing that sequence by hand would be a second
    // implementation of it to keep in step. The frame seam recognises the re-entry and returns
    // without presenting, so only the copy happens.
    // SBR_INTERP60_COPY=1 — OFF BY DEFAULT, because it is not yet correct.
    //
    // It does emit the copy (`copy-to-XFB triggers: 1`, up from 0) and the sub-frame's image does
    // reach the display. But it also turns every MAIN present black, which exposed the real
    // ordering problem: TDisplay::endRendering calls waitForRetrace FIRST and IssueGXCopyDisp
    // SECOND, and the frame seam IS waitForRetrace -- so the main present has always happened
    // BEFORE the tick's own EFB->XFB copy. That only looked right because the display kept showing
    // the previously copied XFB; once the sub-frame issues a copy of its own (which also clears the
    // EFB), the main present has nothing copied out and comes back black.
    //
    // The fix is to move the presents to after the copy, not to suppress the copy — but that is a
    // change to the frame seam's placement and it is not being made blind at the end of a long
    // session. Left behind a switch so the measurement is reproducible.
    static const bool doCopy = std::getenv("SBR_INTERP60_COPY") != nullptr;
    if (doCopy && g_display && sb_ram_fast(g_display)) {
        cpu.gpr[3] = g_display;
        func_802f80d0(cpu);
    }

    present();

    camera_restore(camSave);

    // Pass 2: the true pose, entered again so the NEXT tick's draw lists consume tick N and not the
    // midpoint. This is the pass that makes the substitution self-cancelling by construction.
    restore_all();
    if (!noEntry) perform_list(cpu, preEntry, cue, gfx);

    // Did the re-issue move the view, and did the camera take part?
    {
        float viewAfter[12];
        int changed = 0;
        float maxd = 0.0f;
        for (int i = 0; i < 12; ++i) {
            viewAfter[i] = guest_f32(gfx + OFF_VIEWMTX + (u32)i * 4);
            const float d = viewAfter[i] - viewBefore[i];
            if (d != 0.0f) { ++changed; if (d > maxd || -d > maxd) maxd = d < 0 ? -d : d; }
        }
        static long n = 0;
        if (++n <= 3 || (n % 600) == 0)
            lucent::info("i60sub",
                         "view across re-issue #{}: {} of 12 elements changed (max |d|={:.4f}), "
                         "camera dispatched {}x inside the sub-frame{}",
                         n, changed, (double)maxd, g_camDispatches,
                         changed == 0 ? "  <-- the view is UNCHANGED: no camera field can reach "
                                        "this sub-frame" : "");
        const unsigned long xfb = sbr_gxfifo_xfb_copies() - xfbBefore;
        if (++n <= 4 || (n % 600) == 0)
            lucent::info("i60sub",
                         "  copy-to-XFB triggers emitted by this sub-frame: {}{}", xfb,
                         xfb == 0 ? "  <-- NONE. The sub-frame rendered into the EFB and was never "
                                    "copied out, so the display keeps showing the previous image "
                                    "however much geometry was emitted." : "");
    }

    g_inSubframe = false;
    cpu.gpr[1] = savedSp;
    ++g_subframes;
    // Reset for the NEXT tick's draw block -- AFTER this sub-frame has consumed them, never before.
    // The draw block is recorded EARLY in a call and the seam runs at the end of it, so clearing
    // these on entry throws away the very recording being used (measured: rendered=0, refused=1200,
    // every tick refusing for want of the TGraphics it had just captured).
    g_lastDrawN = g_drawN;
    g_drawN = 0;
    g_gfxValid = false;
}

// Called from native_frame.cpp's present path, after aurora has consumed the frame's GX stream.
// The frame seam asks this before doing any of its own work: inside a sub-frame the game's
// endRendering is being called only for its COPY, and a nested present would end the very frame the
// sub-frame is still building.
extern "C" int sbr_interp60_in_subframe() { return g_inSubframe ? 1 : 0; }

extern "C" void sbr_interp60_restore() {
    if (!enabled()) return;
    if (follow_obj() && g_followLines <= 120) { ++g_followLines;
        lucent::info("i60follow", "  ---------------- PRESENT ----------------"); }
    if (trace_on() && (long)VIGetRetraceCount() >= trace_start_present() && g_tracePresents <= 3) {
        trace_flush_run();
        ++g_tracePresents;
        lucent::info("i60trace", "PRESENT  (end of tick {})", g_tracePresents);
    }
    if (lists_on() && (long)VIGetRetraceCount() >= trace_start_present() && g_listTicks <= 2) {
        ++g_listTicks;
        lucent::info("i60lists", "PRESENT  (end of tick {}; {} outermost perform calls so far)",
                     g_listTicks, g_listLines);
        if (g_listLines == 0)
            lucent::info("i60lists", "  NOTE: zero outermost calls were seen this tick -- the "
                                     "sub-frame body cannot be built from a sequence that is empty");
        g_listSeq = 0;
        if (g_listTicks == 2) resolve_mardir();   // after a full tick has populated the seen-set
    }
}

// Capture the TDisplay the game is rendering through. The sub-frame needs it to issue its own
// EFB->XFB copy, and there is no symbol for the global; the object that endRendering is called on
// IS the one, so take it from there rather than resolving a pointer.
namespace {
void end_rendering(CPUState& cpu) {
    g_display = (u32)cpu.gpr[3];
    func_802f80d0(cpu);
    // The copy has now been issued. Under SBR_PRESENT_AFTER_COPY this is where the frame is
    // actually presentable; without it this call does nothing. Never during a sub-frame, whose own
    // endRendering call exists only to emit a copy.
    if (!g_inSubframe) sbr_frame_present_now();
}
} // namespace


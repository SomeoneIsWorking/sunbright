// SBR_INTERP60_ALPHA: write lerp(prev, cur, alpha) into the guest transform for the draw phase.
// Unset means snapshot-only (read nothing back). alpha=1.0 MUST be pixel-identical to unset --
// that is the control for the write path itself, before interpolation is attempted. alpha=0.0
// renders the PREVIOUS tick's pose and must visibly differ, or the write is reaching nothing.
float alpha_setting() {
    static const float a = [] {
        const char* e = std::getenv("SBR_INTERP60_ALPHA");
        return e ? (float)std::atof(e) : -1.0f;
    }();
    return a;
}

// SBR_INTERP60_ALPHA_CAM / SBR_INTERP60_ALPHA_ACT: the ABLATION. Both default to
// SBR_INTERP60_ALPHA, so setting only the global alpha behaves exactly as before and the split
// cannot change a result nobody asked to split.
//
// WHY IT EXISTS. alpha=1.0 reproduces the following main frame to 0.075 per channel while alpha=0.0
// lands only ~28% of the way back toward the preceding one, and CAMTRACE proves the camera itself
// moves a FULL tick between those alphas. So ~72% of the image is held by something else -- and
// "animation phase / the pre-renders / particles" is a list of three suspects, not a finding.
// Driving the two populations independently attributes the deficit instead of arguing it.
//
// ITS CONTROL: cam=act=<a> must reproduce the single-alpha result for the same <a> exactly. If it
// does not, the split itself changed something and every ablation number taken with it is noise.
float alpha_of(const char* var) {
    const char* e = std::getenv(var);
    return e ? (float)std::atof(e) : alpha_setting();
}
float alpha_cam() {
    static const float a = alpha_of("SBR_INTERP60_ALPHA_CAM");
    return a;
}
float alpha_act() {
    static const float a = alpha_of("SBR_INTERP60_ALPHA_ACT");
    return a;
}

